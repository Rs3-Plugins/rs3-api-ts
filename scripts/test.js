        assert.equal(registryDeps.devDependencies["rs3-api-prettyui"], `^${require(path.join(root, "packages", "prettyui", "package.json")).version}`, "--registry writes a version range for the declarations too");

        let badDep = false;
        try {
            run("init bad-dep --yes --deps notalibrary", scratch);
        } catch (error) {
            badDep = true;
            assert.match(String(error.stderr), /--deps: "notalibrary" is not in the known library list/);
        }
        assert.ok(badDep, "unknown bare dependency names are rejected");

