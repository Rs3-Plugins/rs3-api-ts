// Builds the example with the CLI and asserts on the Lua that comes out.
const assert = require("node:assert/strict");
const { execSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const example = path.join(root, "examples", "hello");
const cliRoot = path.join(root, "packages", "cli");
const cli = path.join(cliRoot, "dist", "index.js");

function run(args, cwd) {
    return execSync(`node "${cli}" ${args}`, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
}

function read(relative) {
    return fs.readFileSync(path.join(example, "dist", relative), "utf8");
}

function pluginLuaOf(files, suffix) {
    const file = files.find((f) => f.endsWith(suffix) && f.includes("rs3-api-extended"));
    assert.ok(file, `${suffix} from rs3-api-extended present in output`);
    return fs.readFileSync(file, "utf8");
}

const FIXTURE_MODULE = `import { vars } from "rs3-api-extended";

const VARP = 4735;
const BITS = (1 << 19) | (1 << 20);
const TRACKED: SkillType[] = [SkillType.ATTACK, SkillType.DEFENCE];

let request: HTTPRequest | undefined;

export function tick() {
    const current = request;
    if (current !== undefined) {
        if (current.finished) {
            print(current.data);
            request = undefined;
        }
        return;
    }
    const value = vars.VarPlayer.FromID(VARP).value;
    const bits = typeof value === "number" ? value : 0;
    if ((bits & BITS) !== 0) {
        send();
    }
    for (const skill of TRACKED) {
        print(Player.GetXPUncapped(skill));
    }
    PersistentDB.SetInt("ticks", 1);
}

export function init() {
    Event.GameStateChanged.Subscribe(onGameState);
}

export function shutdown() {
    Event.GameStateChanged.Unsubscribe(onGameState);
    if (request !== undefined) {
        request.Cancel();
    }
}

function onGameState(event: GameStateChangedEvent) {
    if (event.newState === GameState.GAME) {
        print("fixture is in game");
    }
}

function send() {
    const r = new HTTPRequest(Plugin.urls.api);
    r.AddHeader("Content-Type", "application/json");
    r.Post("{}", noop, noop);
    request = r;
}

function noop() {}
`;

function luaFiles(dir) {
    const out = [];
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) out.push(...luaFiles(full));
        else if (entry.name.endsWith(".lua")) out.push(full);
    }
    return out;
}

main().catch((error) => {
    console.error(error);
    process.exit(1);
});

